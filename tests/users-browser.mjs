async function cookieFor(userId) {
  const now = new Date(), token = randomUUID();
  await fixture.repo.store.db.insert(s.session).values({ id: randomUUID(), userId, token, createdAt: now, updatedAt: now, expiresAt: new Date(Date.now() + 86400000) });
  return (await serializeSignedCookie("better-auth.session_token", token, authConfig.BETTER_AUTH_SECRET, { path: "/" })).split(";")[0];
}
async function login(context, cookie) {
  const split = cookie.indexOf("=");
  await context.addCookies([{ name: cookie.slice(0, split), value: cookie.slice(split + 1), url: fixture.base }]);
}

test("HTTP usuarios: sesión, autorización, origen, compatibilidad del selector y conflictos", async () => {
  const member = await addUser(fixture.repo, "users-api-member"), memberCookie = await cookieFor(member.id);
  const p = (await fixture.repo.execute({ type: "project.create", name: "Proyecto API", description: "", icon: "P", color: "#059669" }, actor)).createdId;
  const endpoint = `${fixture.base}/api/users/${member.id}/projects`;
  assert.equal((await fetch(endpoint)).status, 401);
  assert.equal((await fetch(endpoint, { headers: { Cookie: memberCookie } })).status, 403);
  assert.equal((await fetch(fixture.base + "/api/users", { headers: { Cookie: memberCookie } })).status, 403);
  const get = await fetch(endpoint, { headers: { Cookie: fixture.cookie } });
  assert.match(get.headers.get("cache-control"), /no-store/);
  const snapshot = await get.json();
  const send = (body, extra = {}) => fetch(endpoint, { method: "PATCH", headers: { Cookie: fixture.cookie, "Content-Type": "application/json", Origin: fixture.base, ...extra }, body: JSON.stringify(body) });
  const payload = { revision: snapshot.revision, addProjectIds: [p], removeProjectIds: [] };
  assert.equal((await send(payload, { Origin: "https://evil.test" })).status, 403);
  assert.equal((await send({ ...payload, addProjectIds: ["missing"] })).status, 404);
  assert.equal((await send(payload)).status, 200);
  assert.equal((await send(payload)).status, 409);
  const list = await (await fetch(fixture.base + "/api/users", { headers: { Cookie: fixture.cookie } })).json();
  assert.ok(list.users.find(u => u.id === member.id).projectAccess.some(a => a.projectId === p));
  const legacy = await (await fetch(`${fixture.base}/api/users?projectId=${p}`, { headers: { Cookie: fixture.cookie } })).json();
  assert.ok(legacy.users.some(u => u.id === member.id)); assert.ok(legacy.members.includes(member.id));
  const direct = await fetch(fixture.base + "/api/invitations", { method: "POST", headers: { Cookie: fixture.cookie, Origin: fixture.base, "Content-Type": "application/json" }, body: JSON.stringify({ email: " USERS-API-MEMBER@EXAMPLE.COM ", projectIds: [p] }) });
  assert.equal(direct.status, 200); assert.equal((await direct.json()).kind, "assigned");
  const page = await fetch(fixture.base + "/users", { headers: { Cookie: memberCookie }, redirect: "manual" });
  assert.equal(page.status, 307); assert.equal(page.headers.get("location"), "/projects");
});

